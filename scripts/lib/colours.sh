#!/usr/bin/env bash

# The escape code that switches terminal text to green.
GREEN=$'\033[0;32m'
# The escape code that switches terminal text to purple.
PURPLE=$'\033[0;35m'
# The escape code that switches terminal text to yellow.
YELLOW=$'\033[0;33m'
# The escape code that switches terminal text to red.
RED=$'\033[0;31m'
# The escape code that switches terminal text back to the default colour.
RESET_COLOUR=$'\033[0m'
